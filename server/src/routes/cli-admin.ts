/**
 * CLI 管理面补充端点（S9，设计 kb-agent-upgrade §6.1）
 *
 * `GET /api/cli/info` 与 `POST /api/cli/install-shim`：desktop token 域
 * （与 S8 routes/cli.ts 的 enable/rotate 同一守卫语义——CLI 令牌不能
 * 自我提权，带 X-Cli-Token → 403 cli_forbidden_route，desktop token
 * timing-safe 校验，缺失/错误 → 401）。
 *
 * 挂载顺序（index.ts）：本文件必须挂在 cliRoutes **之前**。cliRoutes
 * 内部的 `use('/api/cli/*')` CLI 令牌中间件在 Hono 中按注册顺序执行，
 * 本文件的静态路由先注册先返回即不受其拦截——与 cliRoutes 内
 * enable/rotate 先注册再挂 use 的策略一致（见 S8 报告挂载图）。
 *
 * shim 机制（§6.1 最小路径，S9 评估结论）：
 *  - `<dataRoot>/bin/feishu-sync`（POSIX sh，0755）与
 *    `feishu-sync.cmd`（Windows）各写一份——目标平台按自身习惯取用，
 *    不做平台探测（用户可能为远端/容器准备另一平台的入口）。
 *  - 内容 = 固定环境（FEISHU_SYNC_HOME 指向数据根；打包版附
 *    ELECTRON_RUN_AS_NODE=1）+ exec '<运行时>' '<dist/cli/feishu-sync-cli.cjs>' "$@"
 *    。开发版运行时 = 当前 Node（process.execPath）；打包版 = Electron
 *    可执行文件（process.versions.electron 存在时）。
 *  - 不改用户 PATH：响应只返回追加提示（pathHint），由用户自行决定。
 */

import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { fileURLToPath } from 'node:url';
import { Hono } from 'hono';
import type { Context } from 'hono';
import type { CliEndpoint } from '../cli-endpoint.js';
import type { ConfigManager } from '../modules/config-manager.js';
import { CLI_TOKEN_HEADER } from '../middleware/cli-auth.js';

export interface CliAdminDeps {
  desktopToken: string;
  cliEndpoint: CliEndpoint;
  configManager: ConfigManager;
  dataRoot: string;
}

function timingSafeTokenEqual(provided: string, expected: string): boolean {
  const a = Buffer.from(provided, 'utf-8');
  const b = Buffer.from(expected, 'utf-8');
  if (a.length !== b.length) return false;
  return crypto.timingSafeEqual(a, b);
}

/** 与 routes/cli.ts 的 desktopGuard 同语义（该工厂未导出，此处等价复刻）。 */
function desktopGuard(desktopToken: string) {
  return async (c: Context): Promise<Response | null> => {
    if (c.req.header(CLI_TOKEN_HEADER) !== undefined) {
      return c.json(
        { error: 'cli_forbidden_route', message: 'CLI 令牌不能管理命令行访问（请在应用设置中操作）' },
        403,
      );
    }
    const provided = c.req.header('X-Desktop-Token') ?? '';
    if (!timingSafeTokenEqual(provided, desktopToken)) {
      return c.json({ error: 'Unauthorized' }, 401);
    }
    return null;
  };
}

/**
 * dist 根：本文件编译后位于 dist/routes/cli-admin.js（与 routes/kb.ts 同法）。
 * vitest/tsx 从 src 运行时上溯得到 src/，此时 CLI 产物在
 * <serverRoot>/dist/cli/（构建链产物）——两个候选都探测，dev-src 不误报。
 */
function cliScriptCandidates(): string[] {
  const moduleRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
  const serverRoot = path.resolve(moduleRoot, '..');
  return [
    path.join(moduleRoot, 'cli', 'feishu-sync-cli.cjs'),
    path.join(serverRoot, 'dist', 'cli', 'feishu-sync-cli.cjs'),
  ];
}

function cliScriptPath(): string {
  return cliScriptCandidates().find((candidate) => fs.existsSync(candidate)) ?? cliScriptCandidates()[0];
}

function posixQuote(value: string): string {
  return `'${value.replaceAll("'", `'\\''`)}'`;
}

export interface ShimPayload {
  posix: string;
  cmd: string;
}

/** 组装 shim 脚本内容（导出供测试断言；不落盘）。 */
export function buildShimScripts(input: {
  command: string;
  cliScript: string;
  dataRoot: string;
  electron: boolean;
}): ShimPayload {
  const envLines = [
    `export FEISHU_SYNC_HOME=${posixQuote(input.dataRoot)}`,
    ...(input.electron ? ['export ELECTRON_RUN_AS_NODE=1'] : []),
  ];
  const posix = [
    '#!/bin/sh',
    '# feishu-sync CLI shim —— 由 feishu-sync 应用生成；重新生成请使用应用设置。',
    '# 用法示例：feishu-sync status --json',
    ...envLines,
    `exec ${posixQuote(input.command)} ${posixQuote(input.cliScript)} "$@"`,
    '',
  ].join('\n');

  const cmd = [
    '@echo off',
    'rem feishu-sync CLI shim - generated by feishu-sync app',
    `set "FEISHU_SYNC_HOME=${input.dataRoot}"`,
    ...(input.electron ? ['set "ELECTRON_RUN_AS_NODE=1"'] : []),
    `"${input.command}" "${input.cliScript}" %*`,
    'exit /b %ERRORLEVEL%',
    '',
  ].join('\r\n');
  return { posix, cmd };
}

function pathHint(binDir: string): string {
  if (process.platform === 'win32') {
    return `将 ${binDir} 加入 PATH（系统设置 → 环境变量，或 setx PATH "%PATH%;${binDir}"）后在命令行运行 feishu-sync`;
  }
  return `将 ${binDir} 加入 PATH（如在 shell 配置中追加 export PATH="${binDir}:$PATH"）后可直接运行 feishu-sync`;
}

function runtimeCommand(): { command: string; env: Record<string, string> } {
  // 打包版：process.execPath = Electron 可执行文件（RunAsNode 模式跑 cli.cjs，
  // 与 kb-mcp 推荐配置一致）；开发/standalone：当前 Node。
  const isElectron = Boolean(process.versions.electron);
  return {
    command: process.execPath,
    env: isElectron ? { ELECTRON_RUN_AS_NODE: '1' } : {},
  };
}

export function cliAdminRoutes(deps: CliAdminDeps): Hono {
  const routes = new Hono();
  const requireDesktop = desktopGuard(deps.desktopToken);
  const binDir = path.join(deps.dataRoot, 'bin');
  const shimPath = path.join(binDir, 'feishu-sync');
  const cmdPath = path.join(binDir, 'feishu-sync.cmd');

  routes.get('/api/cli/info', async (c) => {
    const denied = await requireDesktop(c);
    if (denied) return denied;
    const { command, env } = runtimeCommand();
    const cliScript = cliScriptPath();
    return c.json({
      enabled: deps.configManager.getConfig()?.cli?.enabled === true,
      endpointPublished: deps.cliEndpoint.isPublished(),
      endpointFile: deps.cliEndpoint.endpointFilePath,
      cliAvailable: fs.existsSync(cliScript),
      cliScript,
      shimInstalled: fs.existsSync(shimPath) || fs.existsSync(cmdPath),
      shimPath,
      command,
      args: [cliScript],
      env,
      pathHint: pathHint(binDir),
    });
  });

  routes.post('/api/cli/install-shim', async (c) => {
    const denied = await requireDesktop(c);
    if (denied) return denied;
    const cliScript = cliScriptPath();
    if (!fs.existsSync(cliScript)) {
      return c.json(
        {
          error: 'cli_script_missing',
          message: `CLI 打包产物不存在（${cliScript}）；请先完成应用构建（server build）`,
        },
        409,
      );
    }
    const { command, env } = runtimeCommand();
    const scripts = buildShimScripts({
      command,
      cliScript,
      dataRoot: deps.dataRoot,
      electron: Boolean(process.versions.electron),
    });
    try {
      fs.mkdirSync(binDir, { recursive: true });
      fs.writeFileSync(shimPath, scripts.posix, { encoding: 'utf-8', mode: 0o755 });
      fs.chmodSync(shimPath, 0o755); // writeFileSync mode 受 umask 影响，显式收拢
      fs.writeFileSync(cmdPath, scripts.cmd, { encoding: 'utf-8' });
    } catch (error) {
      return c.json(
        {
          error: 'shim_install_failed',
          message: `shim 写入失败（${shimPath}）：${error instanceof Error ? error.message : String(error)}`,
        },
        500,
      );
    }
    return c.json({
      installed: true,
      shimPath,
      cmdPath,
      command,
      args: [cliScript],
      env,
      pathHint: pathHint(binDir),
    });
  });

  return routes;
}
